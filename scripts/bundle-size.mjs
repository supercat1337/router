// @ts-check

// scripts/bundle-size.mjs
//
// Measures per-entry sizes of dist/*.esm.js and dist/*.esm.bundle.js
// (minified, minified+gzip) and writes a table into README.md between
// BUNDLE_SIZE_START/END markers. Optionally updates a bundle-size badge
// between BUNDLE_BADGE_START/END markers, if those are present.
//
// Usage:
//   node scripts/bundle-size.mjs           # update README (idempotent)
//   node scripts/bundle-size.mjs --check   # exit 1 if README is out of date
//
// Requires `dist/` — run `npm run build` first.
//
// Sizes: SI (KB = 1000), gzip level 9 — matches bundlephobia / npm convention.
// Local-only: no CI. `prepublishOnly` -> `preflight` is the only hard gate.

import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { transformSync } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const README = join(ROOT, 'README.md');

const SIZE_START = '<!-- BUNDLE_SIZE_START -->';
const SIZE_END = '<!-- BUNDLE_SIZE_END -->';
const BADGE_START = '<!-- BUNDLE_BADGE_START -->';
const BADGE_END = '<!-- BUNDLE_BADGE_END -->';

/** [label shown in README, base name in dist/ without extension]. */
const ENTRIES = [
    ['@supercat1337/router', 'router'],
    ['@supercat1337/router/adapters', 'adapters'],
    ['@supercat1337/router/links', 'links'],
    ['@supercat1337/router/guard', 'guard'],
    ['@supercat1337/router/active-links', 'active-links'],
    ['@supercat1337/router/testing', 'testing'],
    ['@supercat1337/router/ssr', 'ssr'],
];

/** SI bytes -> human. KB = 1000, MB = 1e6. */
function fmt(bytes) {
    if (bytes < 1000) return `${bytes} B`;
    if (bytes < 1_000_000) return `${(bytes / 1000).toFixed(1)} KB`;
    return `${(bytes / 1_000_000).toFixed(1)} MB`;
}

/** Minify + gzip one file from dist/. Throws a helpful error if missing. */
async function measureFile(relPath) {
    let code;
    try {
        code = await readFile(join(ROOT, relPath), 'utf8');
    } catch (e) {
        if (e.code === 'ENOENT') {
            throw new Error(
                `${relPath} not found. Run \`npm run build\` before \`npm run bundle-size\`.`
            );
        }
        throw e;
    }
    const { code: min } = transformSync(code, { minify: true, format: 'esm' });
    const minBytes = Buffer.byteLength(min, 'utf8');
    const gzBytes = gzipSync(Buffer.from(min, 'utf8'), { level: 9 }).length;
    return { min: minBytes, gz: gzBytes };
}

/** Measure both .esm.js and .esm.bundle.js for one entry. */
async function measureEntry(base) {
    const esm = await measureFile(`dist/${base}.esm.js`);
    const bundle = await measureFile(`dist/${base}.esm.bundle.js`);
    return {
        esm: esm.min,
        esmGz: esm.gz,
        bundle: bundle.min,
        bundleGz: bundle.gz,
    };
}

/** Build the size table block (with markers). */
async function buildSizeBlock() {
    const rows = [];
    for (const [label, base] of ENTRIES) {
        const m = await measureEntry(base);
        rows.push(
            `| \`${label}\` | ${fmt(m.esm)} | ${fmt(m.esmGz)} | ${fmt(m.bundle)} | ${fmt(
                m.bundleGz
            )} |`
        );
    }
    return [
        SIZE_START,
        '<!-- generated by scripts/bundle-size.mjs — do not edit -->',
        '| Entry | min esm | min esm+gz | min bundle | min bundle+gz |',
        '| --- | ---: | ---: | ---: | ---: |',
        ...rows,
        '',
        '_`esm` — per-entry module, external deps excluded (for `core` and `/guard` add ~1.5 KB gzip for `@supercat1337/event-emitter`). `bundle` — per-entry, all deps inlined. `min` — minified (esbuild). `gz` — gzip level 9. Generated by `npm run bundle-size`; do not edit by hand._',
        SIZE_END,
    ].join('\n');
}

/** Build the badge block (core min bundle+gz). Optional — only if markers exist. */
async function buildBadgeBlock() {
    const core = await measureEntry('router');
    const message = encodeURIComponent(`${fmt(core.bundleGz)} min+gz`);
    const url = `https://img.shields.io/badge/core-${message}-blue`;
    return [
        BADGE_START,
        '<!-- generated by scripts/bundle-size.mjs — do not edit -->',
        `![core bundle size](${url})`,
        BADGE_END,
    ].join('\n');
}

/** Replace marked block. Returns `null` if markers are absent / out of order. */
function replaceBlock(text, start, end, replacement) {
    const i = text.indexOf(start);
    const j = text.indexOf(end);
    if (i < 0 || j < 0 || j < i) return null;
    return text.slice(0, i) + replacement + text.slice(j + end.length);
}

async function main() {
    const check = process.argv.includes('--check');

    const readme = await readFile(README, 'utf8');

    // Size table — required.
    const sizeBlock = await buildSizeBlock();
    let next = replaceBlock(readme, SIZE_START, SIZE_END, sizeBlock);
    if (next === null) {
        throw new Error(
            `README.md: markers ${SIZE_START} / ${SIZE_END} not found (or out of order)`
        );
    }

    // Badge — optional. If markers are absent, leave README untouched.
    const badgeBlock = await buildBadgeBlock();
    const withBadge = replaceBlock(next, BADGE_START, BADGE_END, badgeBlock);
    if (withBadge !== null) next = withBadge;

    if (next === readme) {
        console.log('README.md bundle size unchanged.');
        return;
    }
    if (check) {
        throw new Error('README.md bundle size is out of date. Run: npm run bundle-size');
    }
    await writeFile(README, next);
    console.log('README.md bundle size updated.');
}

main().catch(e => {
    console.error(e.message ?? e);
    process.exit(1);
});
